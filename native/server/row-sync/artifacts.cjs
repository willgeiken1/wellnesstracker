// Offline artifact generation only. Does not open a database or read configuration.
const { readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');
const { createHash } = require('node:crypto');
const sources = ['0001_row_sync.sql', '0002_v1_columns.sql'];
const files = [...sources, 'apply-0001-0002.sql', 'rollback-0001-0002.sql'];
const read = name => readFileSync(join(__dirname, name), 'utf8');
function buildApply() {
  const bodies = sources.map(name => {
    const source = read(name);
    // Intentionally narrow: reject changed transaction structure for human review.
    if ((source.match(/^BEGIN;$/gm) || []).length !== 1 ||
        (source.match(/^COMMIT;$/gm) || []).length !== 1 || !source.trimEnd().endsWith('COMMIT;')) {
      throw new Error(`Review transaction boundaries in ${name}`);
    }
    return `-- Source: ${name}\n${source.replace(/^BEGIN;\n/m, '').replace(/^COMMIT;\s*$/m, '').trimEnd()}\n`;
  });
  return '-- Generated by artifacts.cjs; review sources and this exact artifact.\n-- Initial apply only; existing names fail. Run with stop-on-error.\nBEGIN;\n\n' + bodies.join('\n') + '\nCOMMIT;\n';
}
function ledger() {
  return files.map(name => `${createHash('sha256').update(readFileSync(join(__dirname,name))).digest('hex')}  ${name}`).join('\n')+'\n';
}
function verifyLedger() {
  if (read('SHA256SUMS') !== ledger()) throw new Error('Row-sync SHA-256 ledger mismatch; review changes and regenerate artifacts');
  return true;
}
module.exports = { buildApply, verifyLedger };
if (require.main === module) {
  if (process.argv[2] === '--write' && process.argv.length === 3) {
    writeFileSync(join(__dirname,'apply-0001-0002.sql'), buildApply());
    writeFileSync(join(__dirname,'SHA256SUMS'), ledger());
  } else if (process.argv.length === 2) {
    verifyLedger();
    if (read('apply-0001-0002.sql') !== buildApply()) throw new Error('Regenerate wrapper after source review');
    console.log('Wrapper and SHA-256 ledger verified.');
  } else throw new Error('Usage: node artifacts.cjs [--write]');
}
