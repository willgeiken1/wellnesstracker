#!/usr/bin/env node
/* Turns design/icons/insight-icons.json, the one source for the Insight icon set, into the files the apps read:
     native/src/components/icon-data.ts   shapes for react-native-svg (iPhone, Android, web build of the native app)
     logger/js/shared/icon-set.js         inner SVG markup for the web app
   and refreshes every <svg data-icon="name"> in logger/index.html, which is static HTML and cannot import a module.
   No dependencies. Run from anywhere: node native/scripts/gen-icons.cjs   (add --check to fail when a file is stale) */
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..', '..');
const SOURCE = 'design/icons/insight-icons.json';
const SHAPES = new Set(['path', 'circle', 'rect', 'line', 'ellipse']);
const ATTRS = new Set(['d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'width', 'height', 'x1', 'y1', 'x2', 'y2',
  'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'fill-rule', 'fill-opacity', 'stroke-opacity', 'opacity']);
const TEXT = new Set(['d', 'fill', 'stroke', 'stroke-linecap', 'stroke-linejoin', 'fill-rule']);
const camel = name => name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());

function parse(name, markup) {
  const shapes = [];
  const rest = markup.replace(/<([a-z]+)((?:\s+[a-z0-9-]+="[^"]*")*)\s*\/>/g, (_, type, body) => {
    if (!SHAPES.has(type)) throw new Error(`${name}: <${type}> is not a shape this set may use`);
    const attrs = {};
    for (const [, key, value] of body.matchAll(/([a-z0-9-]+)="([^"]*)"/g)) {
      if (!ATTRS.has(key)) throw new Error(`${name}: attribute ${key} is not one this set may use`);
      if ((key === 'fill' || key === 'stroke') && value !== 'none' && value !== 'currentColor') throw new Error(`${name}: ${key} must be none or currentColor, so the icon takes its colour from where it is used`);
      if (!TEXT.has(key) && !Number.isFinite(Number(value))) throw new Error(`${name}: ${key}="${value}" is not a number`);
      attrs[camel(key)] = TEXT.has(key) ? value : Number(value);
    }
    shapes.push({ type, attrs });
    return '';
  });
  if (rest.trim() || !shapes.length) throw new Error(`${name}: could not read "${rest.trim().slice(0, 40)}"`);
  return shapes;
}

const set = JSON.parse(fs.readFileSync(path.join(root, SOURCE), 'utf8'));
const names = Object.keys(set.icons);
for (const name of names) if (!/^[a-z][a-z0-9-]*$/.test(name)) throw new Error(`"${name}" is not a usable icon name`);
const header = `GENERATED by native/scripts/gen-icons.cjs from ${SOURCE}. Do not edit: change the JSON and run the script.`;

const native = `/* ${header} */
export type IconShape = { type: 'path' | 'circle' | 'rect' | 'line' | 'ellipse'; attrs: Readonly<Record<string, string | number>> };
/** The stroke every line in the set is drawn with, in a ${set.viewBox.split(' ')[2]} box. */
export const ICON_STROKE = ${set.strokeWidth};
export const iconData = {
${names.map(name => `  ${JSON.stringify(name)}: ${JSON.stringify(parse(name, set.icons[name]))},`).join('\n')}
} as const satisfies Record<string, readonly IconShape[]>;
`;

const web = `/* ${header} */
/** The stroke every line in the set is drawn with, in a ${set.viewBox.split(' ')[2]} box. */
export const ICON_STROKE = ${set.strokeWidth};
/** Icon name to the inner markup of a ${set.viewBox} SVG that draws in currentColor. */
export const ICON_SET = Object.freeze({
${names.map(name => `  ${JSON.stringify(name)}: ${JSON.stringify(set.icons[name])},`).join('\n')}
});
`;

const pagePath = 'logger/index.html';
const page = fs.readFileSync(path.join(root, pagePath), 'utf8').replace(/(<svg\b[^>]*\bdata-icon="([^"]+)"[^>]*>)[\s\S]*?(<\/svg>)/g, (_, open, name, close) => {
  if (!set.icons[name]) throw new Error(`${pagePath}: no icon named "${name}"`);
  return open + set.icons[name] + close;
});

const outputs = { 'native/src/components/icon-data.ts': native, 'logger/js/shared/icon-set.js': web, [pagePath]: page };
const check = process.argv.includes('--check');
let stale = 0;
for (const [file, text] of Object.entries(outputs)) {
  const full = path.join(root, file);
  const same = fs.existsSync(full) && fs.readFileSync(full, 'utf8') === text;
  if (same) continue;
  if (check) { stale += 1; console.error(`${file} is out of date. Run: node native/scripts/gen-icons.cjs`); } else { fs.writeFileSync(full, text); console.log(`wrote ${file}`); }
}
if (stale) process.exit(1);
if (!check) console.log(`${names.length} icons`);
