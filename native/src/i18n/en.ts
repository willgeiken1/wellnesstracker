export type MessageKey = keyof typeof en;
export function t(key: MessageKey): string { return en[key]; }

export function signOutUnsynced(count: number): string {
  return t(count===1?'signOutUnsynced_one':'signOutUnsynced_other').replace('{count}',String(count));
}

export function equipmentLabel(equipment: import('../core/workout/rules').Equipment) {return t(`equipment_${equipment}`);}

/** Counted logger copy lives here so singular forms cannot drift between screens. */
export function pluralize(count: number, noun: 'set' | 'rep' | 'exercise' | 'token' | 'left') {
  return `${count} ${noun}${count === 1 || noun === 'left' ? '' : 's'}`;
}
export function workingSetsPhrase(count: number) {
  return count === 1 ? 'on your 1 working set' : count === 2 ? 'on both sets' : `on all ${count} working sets`;
}

export function muscleLabel(muscle: string) { return en[`muscle_${muscle}` as keyof typeof en] ?? muscle; }

/** Local time and a short copy number identify controls without exposing row values or IDs. */
export function restoreVersionLabel(row: import('../data/rows').Row, copy: number): string {
  const date = new Date(row.updated_at).toLocaleString('en-US', {
    month:'short', day:'numeric', year:'numeric', hour:'numeric', minute:'2-digit', second:'2-digit',
  });
  return t('restorePreviousVersion').replace('{table}',t(`recoveryTable_${row.table}`))
    .replace('{copy}',String(copy)).replace('{date}',date);
}
